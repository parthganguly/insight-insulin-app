"""Python3 standard-library replay: no numpy, figure, PDF or network required.

Run: python portable_verify.py
Needs portable_inputs.json and portable_expected_snapshot.json beside this file.
The expected snapshot was generated by the separate numpy/source-audit scripts.
"""
import json
import math
from pathlib import Path

HERE=Path(__file__).resolve().parent
data=json.loads((HERE/'portable_inputs.json').read_text(encoding='utf-8'))
expected=json.loads((HERE/'portable_expected_snapshot.json').read_text(encoding='utf-8'))
train=data['training']
x=[math.log1p(-a) for a in train['amylose']]
mx=sum(x)/len(x)
ssx=sum((a-mx)**2 for a in x)
fits={};covs=[]
for state in ('raw','gel'):
    y=[math.log(v) for v in train[state]]
    my=sum(y)/len(y)
    cov=sum((a-mx)*(b-my) for a,b in zip(x,y))
    fits[state]=cov/ssx
    covs.append(cov)
fits['shared']=sum(covs)/(2*ssx)

def trap(values,times):
    return sum((b-a)*(u+v)/2 for a,b,u,v in zip(times,times[1:],values,values[1:]))

fig=data['figure'];scale=fig['high_concentration']/(fig['zero_y']-fig['high_y'])
t=fig['time'][:5]
weights=[(t[1]-t[0])/2]
weights +=[(t[i+1]-t[i-1])/2 for i in range(1,len(t)-1)]
weights +=[(t[-1]-t[-2])/2]
duration=t[-1]-t[0]
signed={};pixel_bounds={}
for arm,ys0 in fig['marker_y'].items():
    ys=ys0[:5]
    concentrations=[scale*(fig['zero_y']-y) for y in ys]
    signed[arm]=trap([c-concentrations[0] for c in concentrations],t)
    coefs=[duration-weights[0]]+[-w for w in weights[1:]]
    signed_px=sum(c*y for c,y in zip(coefs,ys))
    signed_error=fig['marker_uncertainty_px']*sum(abs(c) for c in coefs)
    gross_px=sum(w*(fig['zero_y']-y) for w,y in zip(weights,ys))
    gross_error=duration*(fig['marker_uncertainty_px']+fig['zero_axis_uncertainty_px'])
    pixel_bounds[arm]={'signed_lo':signed_px-signed_error,'gross_hi':gross_px+gross_error}

scores={name:{} for name in expected['marginals']}
for arm,r in data['arms'].items():
    dose=1.21*r['starch'];fraction=1-r['amylose']
    for name in scores:
        value={
          'heated_as_served':dose*fraction**fits['gel'],
          'shared_as_served':dose*fraction**fits['shared'],
          'amylopectin_dose':dose*fraction,
          'total_starch':dose,
          'digestible_starch_derived':1.21*(r['starch']-r['RS']),
          'carbohydrate_paper_definition':1.21*(r['starch']+r['sugar']),
          'available_carbohydrate_derived':1.21*(r['starch']+r['sugar']-r['RS']),
          'equal_serving':1.,
          'heated_fixed_dose':fraction**fits['gel'],
          'shared_fixed_dose':fraction**fits['shared'],
          'amylopectin_fixed_dose':fraction}[name]
        scores[name][arm]=value
margins={};ratios={}
pairs={'HAW_over_LAW_refined':('HAW-R','LAW-R'),'HAW_over_LAW_wholemeal':('HAW-W','LAW-W'),
       'wholemeal_over_refined_LAW':('LAW-W','LAW-R'),'wholemeal_over_refined_HAW':('HAW-W','HAW-R')}
for model,s in scores.items():
    margins[model]={'HAW_over_LAW':(s['HAW-R']+s['HAW-W'])/(s['LAW-R']+s['LAW-W']),
                    'wholemeal_over_refined':(s['LAW-W']+s['HAW-W'])/(s['LAW-R']+s['HAW-R'])}
    ratios[model]={key:s[hi]/s[lo] for key,(hi,lo) in pairs.items()}
bounds={}
for name,high,low in [('refined','HAW-R','LAW-R'),('wholemeal','HAW-W','LAW-W')]:
    h,l=pixel_bounds[high],pixel_bounds[low]
    bounds[name]=[h['signed_lo']/l['gross_hi'],h['gross_hi']/l['signed_lo']]
result={'fit':fits,'signed120':signed,'marginals':margins,'positive_bounds':bounds,'ratios120':ratios}
count=0
def compare(actual,want,path=''):
    global count
    if isinstance(want,dict):
        assert actual.keys()==want.keys(),path
        for k,v in want.items():compare(actual[k],v,path+'/'+k)
    elif isinstance(want,list):
        assert len(actual)==len(want),path
        for i,v in enumerate(want):compare(actual[i],v,path+'/'+str(i))
    else:
        assert math.isclose(actual,want,rel_tol=1e-11,abs_tol=1e-9),(path,actual,want)
        count+=1
compare(result,expected)
table=data['table3_insulin']
result['table3_observed_marginal_ratios']={'HAW_over_LAW':table['HAW']['mean']/table['LAW']['mean'],
                                         'wholemeal_over_refined':table['wholemeal']['mean']/table['refined']['mean']}
result['comparison']={'numeric_fields_checked_against_independent_snapshot':count,'all_match':True,
                      'relative_tolerance':1e-11,'absolute_tolerance':1e-9}
result['assumptions']=data['assumptions']
(HERE/'portable_results.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
print(json.dumps(result,indent=2))
